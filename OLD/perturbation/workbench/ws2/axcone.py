"""Ridge-with-boundary-freedom sub-cones of the weak cone at d = 2.

Family R(dirs): for each direction xi >= 0 (price space) and each level a of v = xi.Q over the
points, the set  {p : xi.Q_p < a} u B  (B any subset of the points on the line xi.Q = a) is
weakly reachable.  Hence y is in the cone generated by these sets iff there are b >= 0 and
jumps J_{k,a} >= 0 with, for every point p,

    sum_k sum_{a > v_kp} J_{k,a}  <=  y_p - b  <=  sum_k sum_{a >= v_kp} J_{k,a}.

(Lemma A of GLOBAL-WS.md.)  dirs = [(1,0),(0,1)] is the axis-parallel family.
"""
