import numpy as np
from scipy.optimize import linprog
from scipy.sparse import lil_matrix

AX = [(1.0, 0.0), (0.0, 1.0)]

def cone_lp(Q, y, dirs=AX, margin=False, tol=1e-9):
    """Q: (T,2) prices, y: (T,) levels.  Returns (feasible, info).  If margin, maximises the
    minimal slack t such that both inequalities hold with slack t (t > 0: strictly inside)."""
    Q = np.asarray(Q, float); y = np.asarray(y, float); T = len(y)
    cols = []   # (k, level index) -> variable
    levels = []; vidx = []
    nv = 0
    for k, xi in enumerate(dirs):
        v = Q @ np.asarray(xi, float)
        lv = np.unique(v); levels.append(lv)
        vidx.append(np.searchsorted(lv, v))
        cols.append(list(range(nv, nv + len(lv)))); nv += len(lv)
    ib = nv; nv += 1
    it = None
    if margin: it = nv; nv += 1
    A = lil_matrix((2 * T, nv)); bvec = np.zeros(2 * T)
    for p in range(T):
        # lower: sum_{a > v} J + b (+t) <= y_p   ; upper: -sum_{a >= v} J - b (+t) <= -y_p
        for k in range(len(dirs)):
            j = vidx[k][p]
            for a in range(j + 1, len(levels[k])): A[2 * p, cols[k][a]] = 1
            for a in range(j, len(levels[k])): A[2 * p + 1, cols[k][a]] = -1
        A[2 * p, ib] = 1; A[2 * p + 1, ib] = -1
        if margin: A[2 * p, it] = 1; A[2 * p + 1, it] = 1
        bvec[2 * p] = y[p]; bvec[2 * p + 1] = -y[p]
    c = np.zeros(nv)
    bounds = [(0, None)] * nv
    if margin: c[it] = -1; bounds[it] = (None, None)
    res = linprog(c, A_ub=A.tocsr(), b_ub=bvec, bounds=bounds, method="highs")
    if res.status != 0: return False, dict(status=res.status, msg=res.message)
    x = res.x
    J = [x[cols[k]] for k in range(len(dirs))]
    info = dict(b=x[ib], J=J, levels=levels, t=(x[it] if margin else None))
    if margin: return x[it] > -tol, info
    return True, info

def check_decomp(Q, y, info, dirs=AX, tol=1e-7):
    """Verify the sandwich inequalities of a returned decomposition."""
    Q = np.asarray(Q, float); y = np.asarray(y, float)
    lo = np.full(len(y), info['b']); hi = np.full(len(y), info['b'])
    for k, xi in enumerate(dirs):
        v = Q @ np.asarray(xi, float); lv = info['levels'][k]; J = info['J'][k]
        for p in range(len(y)):
            lo[p] += J[lv > v[p] + 1e-12].sum(); hi[p] += J[lv >= v[p] - 1e-12].sum()
    return bool(np.all(lo <= y + tol) and np.all(y <= hi + tol)), (y - lo).min(), (hi - y).min()

# ---------------------------------------------------------------- quadrant family
def quad_lp(Q, y, vertices=None, margin=False, tol=1e-9, extra=None, return_lp=False):
    """Family Qd: sets P \\ (v + R^2_+) u B, B a subset of the points on the two boundary rays
    of v (weakly reachable for every v in R^2).  y in cone(Qd) iff there is a measure mu >= 0 on
    vertices with  mu{v : v <= p fails}  <=  y_p - b  <=  mu{v : v < p strictly fails}.
    vertices: list of candidate vertices (default: all (x_p, y_q) combinations of point
    coordinates together with the points themselves).  Coordinates compared exactly (Fractions or
    snapped floats)."""
    Q = np.asarray(Q, float); y = np.asarray(y, float); T = len(y)
    if vertices is None:
        xs = np.unique(Q[:, 0]); ys = np.unique(Q[:, 1])
        vertices = [(a, c) for a in xs for c in ys]
    V = np.asarray(vertices, float); nV = len(V)
    nv = nV + 1 + (1 if margin else 0); ib = nV; it = nV + 1
    A = lil_matrix((2 * T, nv)); bvec = np.zeros(2 * T)
    for p in range(T):
        le = (V[:, 0] <= Q[p, 0] + 1e-12) & (V[:, 1] <= Q[p, 1] + 1e-12)     # v <= p
        lt = (V[:, 0] < Q[p, 0] - 1e-12) & (V[:, 1] < Q[p, 1] - 1e-12)       # v < p strictly
        for j in np.where(~le)[0]: A[2 * p, j] = 1          # lower: mu{v not<= p} + b (+t) <= y_p
        for j in np.where(~lt)[0]: A[2 * p + 1, j] = -1     # upper: -mu{v not< p} - b (+t) <= -y_p
        A[2 * p, ib] = 1; A[2 * p + 1, ib] = -1
        if margin: A[2 * p, it] = 1; A[2 * p + 1, it] = 1
        bvec[2 * p] = y[p]; bvec[2 * p + 1] = -y[p]
    c = np.zeros(nv); bounds = [(0, None)] * nv
    if margin: c[it] = -1; bounds[it] = (None, None)
    res = linprog(c, A_ub=A.tocsr(), b_ub=bvec, bounds=bounds, method="highs")
    if res.status != 0: return False, dict(status=res.status, msg=res.message)
    x = res.x; info = dict(b=x[ib], mu=x[:nV], vertices=V, t=(x[it] if margin else None), res=res)
    if margin: return x[it] > -tol, info
    return True, info
